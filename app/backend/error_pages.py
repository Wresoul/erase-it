"""Кастомные HTML-страницы для ошибок 4xx/5xx при прямой навигации в браузере.

Используются только когда браузер запрашивает страницу напрямую (см. main.py —
разделение по заголовку Accept). Ответы /segment и /inpaint для fetch() из
app.js этот модуль не трогает и остаются в формате JSON.
"""

import html
from pathlib import Path

TEMPLATE_PATH = Path(__file__).resolve().parent.parent / "frontend" / "errors" / "error.html"

_STATUS_INFO = {
    400: ("Некорректный запрос", "Сервер не смог обработать запрос — проверьте отправленные данные."),
    403: ("Доступ запрещён", "У вас нет прав на выполнение этого запроса."),
    404: ("Страница не найдена", "Такой страницы не существует — проверьте адрес."),
    413: ("Файл слишком большой", "Загруженный файл превышает допустимый размер."),
    422: ("Некорректные данные", "Переданные данные не прошли проверку."),
    429: ("Слишком много запросов", "Подождите немного и попробуйте снова."),
    500: ("Внутренняя ошибка сервера", "Что-то пошло не так на нашей стороне. Мы уже разбираемся."),
    502: ("Сервис недоступен", "Не удалось получить ответ от вышестоящего сервиса."),
    503: ("Сервис временно недоступен", "Сервер перегружен или на обслуживании — попробуйте позже."),
}

_DEFAULT_INFO = ("Ошибка", "Запрос не был выполнен.")

_TEMPLATE = TEMPLATE_PATH.read_text(encoding="utf-8")


def render_error_page(status_code: int, detail: str | None = None) -> str:
    title, message = _STATUS_INFO.get(status_code, _DEFAULT_INFO)
    return _TEMPLATE.format(
        status_code=status_code,
        title=html.escape(title),
        message=html.escape(detail or message),
    )
